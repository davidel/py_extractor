"""Assemble the final single-file output from a closure result."""

from __future__ import annotations

import ast

from ..errors import ExtractionError
from ..verify import compile_source
from .closure import Binding, ClosureResult, ExtractedUnit, KeptImport


def _module_alias(unit: ExtractedUnit) -> str | None:
  """Return the alias used to reference a whole-module unit, if any."""
  return None


def emit(
    result: ClosureResult,
    *,
    header: str | None = None,
    include_report: bool = True,
) -> str:
  """Render a :class:`ClosureResult` into a single Python source string.

  The output consists of a header comment, the collected kept imports, the
  inlined definitions (dependency-ordered) and an optional resolution report.

  Raises:
    ExtractionError: If the assembled source is not valid Python.
  """
  lines: list[str] = []
  lines.extend(_render_header(header, result))
  lines.append("")

  import_lines = _render_imports(result.kept_imports)
  if any(binding.kind == "module" for binding in result.bindings):
    # Namespace objects for module bindings are built with SimpleNamespace.
    import_lines.append("import types as _py_extractor_types")
  if import_lines:
    lines.extend(import_lines)
    lines.append("")

  for unit in result.units:
    lines.extend(_render_unit(unit))
    for binding in _bindings_for_unit(result, unit):
      lines.extend(_render_binding(binding))

  if include_report:
    lines.append("")
    lines.extend(_render_report(result))

  source = "\n".join(lines).rstrip() + "\n"

  try:
    # Full compiler check (stronger than ast.parse): catches top-level
    # return/break/yield, duplicate args, etc. that can result from inlining.
    compile_source(source)
  except SyntaxError as exc:  # pragma: no cover - defensive
    raise ExtractionError(f"Generated output is not valid Python: {exc}") from exc
  return source


def _render_header(header: str | None, result: ClosureResult) -> list[str]:
  text = header or "Code extracted by py_extractor."
  out = ["# " + line if line else "#" for line in text.splitlines()]
  out.append("#")
  out.append(f"# Target: {result.target.module}:{result.target.symbol or '<module>'}")
  out.append("#")
  out.append("# WARNING: This file was generated automatically. Review it and the")
  out.append("# provenance notes below before trusting it.")
  return out


def _render_imports(imports: list[KeptImport]) -> list[str]:
  seen: set[str] = set()
  rendered: list[str] = []
  for imp in sorted(imports, key=lambda i: (i.kind, i.module, i.name)):
    line = _render_import(imp)
    if line not in seen:
      seen.add(line)
      rendered.append(line)
  return rendered


def _render_import(imp: KeptImport) -> str:
  if imp.kind == "import":
    if imp.asname and imp.asname != imp.module.split(".")[0]:
      return f"import {imp.module} as {imp.asname}"
    return f"import {imp.module}"
  if imp.asname:
    return f"from {imp.module} import {imp.name} as {imp.asname}"
  return f"from {imp.module} import {imp.name}"


def _render_unit(unit: ExtractedUnit) -> list[str]:
  if unit.symbol is None:
    # Whole-module inline: emit only the top-level definitions/assignments.
    # Import statements are hoisted to the shared header by the closure, so
    # re-emitting them here would duplicate imports and break on dependencies
    # that were rewritten or de-duplicated.
    marker = f"# --- inlined module {unit.module} ({unit.repo_id}:{unit.path}) ---"
    body = _module_definition_source(unit.node)
    if not body.strip():
      return []
    return [marker, body, ""]
  marker = f"# --- {unit.module}:{unit.symbol}  (from {unit.repo_id}:{unit.path}) ---"
  code = ast.unparse(_strip_docstring_possible(unit.node))
  return [marker, code, ""]


def _module_definition_source(node: ast.AST) -> str:
  """Return the source of a module's top-level defs/assignments (no imports)."""
  blocks: list[str] = []
  for stmt in getattr(node, "body", []):
    if isinstance(stmt, (ast.Import, ast.ImportFrom)):
      continue
    if isinstance(stmt,
                  (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Assign, ast.AnnAssign)):
      blocks.append(ast.unparse(stmt))
    # Docstrings / bare expressions / if __name__ blocks are intentionally skipped.
  return "\n\n".join(blocks)


def _bindings_for_unit(result: ClosureResult, unit: ExtractedUnit) -> list[Binding]:
  """Return the bindings whose definition *unit* provides, in stable order."""
  return sorted(
      (b for b in result.bindings if b.unit_key == unit.key),
      key=lambda b: (b.kind, b.local, b.parts),
  )


def _render_binding(binding: Binding) -> list[str]:
  """Render one local-name binding as Python source lines."""
  if binding.kind == "alias":
    return [f"{binding.local} = {binding.target}"]

  # module binding: synthesise a namespace object exposing the inlined members.
  ns = "_py_extractor_types.SimpleNamespace"
  members = "".join(f", {name}={name}" for name in binding.members)
  expr = f"{ns}({members[2:]})" if members else f"{ns}()"
  for part in reversed(binding.parts):
    expr = f"{ns}({part}={expr})"
  return [f"{binding.local} = {expr}"]


def _strip_docstring_possible(node: ast.AST) -> ast.AST:
  """Return *node* unchanged (hook for future docstring/annotation trimming)."""
  return node


def _render_report(result: ClosureResult) -> list[str]:
  lines = ["# " + "=" * 68, "# Resolution report", "# " + "=" * 68]
  lines.append(f"# Definitions inlined: {len(result.units)}")
  for unit in result.units:
    label = f"{unit.module}:{unit.symbol}" if unit.symbol else unit.module
    lines.append(f"#   - {label}  ({unit.repo_id}:{unit.path})")
  if result.kept_imports:
    lines.append(f"# Imports kept as-is: {len(result.kept_imports)}")
    for imp in sorted(result.kept_imports, key=lambda i: (i.module, i.name)):
      lines.append(f"#   - {_render_import(imp)}")
  if result.flags:
    lines.append(f"# Warnings: {len(result.flags)}")
    for flag in result.flags:
      lines.append(f"#   [{flag.kind.value}] {flag.detail}" +
                   (f"  ({flag.location})" if flag.location else ""))
  else:
    lines.append("# Warnings: none")
  lines.append("# " + "=" * 68)
  return lines


__all__ = ["emit"]
